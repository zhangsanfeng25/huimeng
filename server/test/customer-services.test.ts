import test,{after} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';import {tmpdir} from 'node:os';import {join} from 'node:path';
const dir=mkdtempSync(join(tmpdir(),'huimeng-services-'));process.env.DATABASE_PATH=join(dir,'db');
const {db}=await import('../src/core/db.js');await import('../scripts/migrate.js');await import('../scripts/seed.js');
const {serviceAction,serviceList,serviceDetail}=await import('../src/services/customer-services.js');
const {runBusiness}=await import('../src/services/context.js');
const awaitOrders=await import('../src/services/orders.js');
const {readSyncResources}=await import('../src/sync/snapshots.js');
const buyer={id:'U10001',name:'buyer',roles:['USER'],activeRole:'USER'};
const shop=db.prepare('SELECT id,owner_user_id FROM merchants LIMIT 1').get() as any;
const merchant={id:shop.owner_user_id,name:'merchant',roles:['USER','MERCHANT'],merchantId:shop.id,activeRole:'MERCHANT'};
const admin={id:'A0001',name:'admin',roles:['ADMIN'],activeRole:'ADMIN'};
const stranger={...buyer,id:'U10002'};
after(()=>db.close());
function act(actor:any,kind:string,id:string,action:string,payload:any={}){return runBusiness(serviceAction,actor,{...payload,action},{kind,id});}
test('chat fixed pair, private access, idempotency, read state and context validation',()=>{
 const initial=readSyncResources(buyer,'buyerOrders');assert.ok(initial.every(row=>typeof row.after_sale_state==='string'&&typeof row.after_sale_id==='string'),'无售后时使用空字符串，不向手机传 null');
 const a=act(buyer,'conversations','','create',{merchantId:shop.id});assert.equal(a.status,201);const cid=a.data.data.id;
 assert.equal(act(buyer,'conversations','','create',{merchantId:shop.id}).data.data.id,cid);
 assert.throws(()=>serviceDetail(stranger,'conversations',cid,false),/无权/);
 const body={content:'购买前咨询',clientId:'one-message'};
 assert.equal(act(buyer,'conversations',cid,'send',body).status,200);
 assert.equal(act(buyer,'conversations',cid,'send',body).data.reused,true);
 assert.equal(serviceDetail(merchant,'conversations',cid,false).messages.length,1);
 assert.equal(serviceList(merchant,'conversations',false)[0].unread,1);
 act(merchant,'conversations',cid,'read');assert.equal(serviceList(merchant,'conversations',false)[0].unread,0);
 assert.throws(()=>act(buyer,'conversations',cid,'send',{content:'bad',clientId:'bad',orderId:'not-own'}),/订单/);
});
test('feedback private threads, role-limited processing and follow-up reopens',()=>{
 const r=act(buyer,'feedback','','create',{title:'购买问题',content:'请帮助检查',type:'订单问题',clientId:'feedback-1'});assert.equal(r.status,201);const fid=r.data.data.id;
 assert.throws(()=>serviceDetail(stranger,'feedback',fid,false),/无权/);
 assert.throws(()=>act(buyer,'feedback',fid,'resolve'),/无权/);
 act(admin,'feedback',fid,'reply',{content:'已核查',clientId:'reply-1'});act(admin,'feedback',fid,'resolve');
 assert.equal(serviceDetail(buyer,'feedback',fid,false).status,'RESOLVED');
 act(buyer,'feedback',fid,'reply',{content:'补充信息',clientId:'reply-2'});
 assert.equal(serviceDetail(buyer,'feedback',fid,false).status,'PROCESSING');
});
test('after-sales two-stage approval and once-only demo refund and stock',()=>{
 const order=db.prepare('SELECT id,user_id FROM orders WHERE merchant_id=? LIMIT 1').get(shop.id) as any;
 db.prepare("UPDATE orders SET user_id=?,status='PAID',logistics_status='PREPARING' WHERE id=?").run(buyer.id,order.id);
 const payload={orderId:order.id,type:'REFUND_ONLY',reason:'不需要了',description:'整单退款',clientId:'case-1'};
 const r=act(buyer,'after-sales','','create',payload);assert.equal(r.status,201);const aid=r.data.data.id;
 const {orderShip,orderConfirm}=awaitOrders;
 assert.equal(runBusiness(orderShip,merchant,{}, {orderId:order.id}).status,409);
 assert.equal(runBusiness(orderConfirm,buyer,{}, {orderId:order.id}).status,409);
 assert.equal(act(buyer,'after-sales','','create',payload).data.data.id,aid);
 assert.throws(()=>act(stranger,'after-sales',aid,'cancel'),/无权/);
 assert.throws(()=>act(admin,'after-sales',aid,'refund'),/状态/);
 act(merchant,'after-sales',aid,'merchant-review',{approve:true,note:'同意'});
 act(admin,'after-sales',aid,'approve',{note:'审核通过'});
 const before=(db.prepare('SELECT SUM(stock_available) n FROM products').get() as any).n;
 assert.equal(act(admin,'after-sales',aid,'refund').status,200);
 assert.equal(act(admin,'after-sales',aid,'refund').data.reused,true);
 assert.equal((db.prepare('SELECT COUNT(*) n FROM refunds WHERE after_sale_id=?').get(aid) as any).n,1);
 assert.ok((db.prepare('SELECT SUM(stock_available) n FROM products').get() as any).n>before);
 assert.equal(serviceDetail(buyer,'after-sales',aid,false).status,'COMPLETED');
 const projected=readSyncResources(buyer,'buyerOrders').find(r=>r.id===order.id);assert.equal(projected.after_sale_state,'COMPLETED');assert.equal(projected.refunded_cents,r.data.data.amount_cents);
 assert.deepEqual(projected.serviceEvents.map((e:any)=>e.action),['CREATE','merchant-review','approve','refund'],'订单进度必须包含实际售后步骤及退款记录');
 assert.ok(projected.serviceEvents.every((e:any)=>e.createdAt&&e.type==='REFUND_ONLY'));
 const merchantProjection=readSyncResources(merchant,'merchantOrders').find(r=>r.id===order.id);
 assert.deepEqual(merchantProjection.serviceEvents,projected.serviceEvents);
 assert.throws(()=>act(buyer,'after-sales','','create',{...payload,clientId:'case-2'}),/退款/);
});
test('return refund requires logistics then receipt, and admin can decide a merchant rejection',()=>{
 const order=db.prepare('SELECT id FROM orders WHERE merchant_id=? AND id NOT IN (SELECT order_id FROM after_sales) LIMIT 1').get(shop.id) as any;
 db.prepare("UPDATE orders SET user_id=?,status='SHIPPED',logistics_status='IN_TRANSIT' WHERE id=?").run(buyer.id,order.id);
 const r=act(buyer,'after-sales','','create',{orderId:order.id,type:'RETURN_REFUND',reason:'商品问题',clientId:'return-1'});const aid=r.data.data.id;
 act(merchant,'after-sales',aid,'merchant-review',{approve:false,note:'请平台核查'});
 act(admin,'after-sales',aid,'approve',{note:'同意退货',returnAddress:'测试退货地址'});
 assert.throws(()=>act(admin,'after-sales',aid,'refund'),/状态/);
 act(buyer,'after-sales',aid,'return',{carrier:'测试快递',trackingNo:'TEST123'});
 act(merchant,'after-sales',aid,'receive');act(admin,'after-sales',aid,'refund');
 assert.equal(serviceDetail(buyer,'after-sales',aid,false).status,'COMPLETED');
});
