function command(action, args = [], success = true) {
  const result = spawnSync(process.execPath, [script, action, ...args], { cwd, env, encoding: 'utf8' });
  if (success) assert.equal(result.status, 0, result.stderr);
  else assert.notEqual(result.status, 0, 'Invalid restore must fail');
  return success ? JSON.parse(result.stdout) : result.stderr;
}
